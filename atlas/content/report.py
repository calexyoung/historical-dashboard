"""``docs/v2/events-review.md``: the migration review of v1's Events as a page for Alex
(PLAN M19; ADR 0033).

    python -m atlas.content.report --write     write the page
    python -m atlas.content.report --check     exit 1 if the page is out of date

The page is ``content/events/migration-review.json`` beside the Events as they are now: every
Event the review listed, with the words found, Codex's reason and the proposed wording, and
every citation that has no archived copy, with the reason.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from . import events as E
from . import wordlist as W

PAGE = E.ROOT / "docs" / "v2" / "events-review.md"
REVIEW = E.EVENTS_DIR / "migration-review.json"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(events_dir: Path | None = None, review_path: Path | None = None) -> str:
    events, problems = E.load_events(events_dir)
    if problems:
        raise ValueError(problems[0])
    review = json.loads((review_path or REVIEW).read_text(encoding="utf-8"))
    by_id = {event["id"]: event for event in events}
    listed = [row for row in review["events"] if row["outcome"] == "listed"]
    passed = len(review["events"]) - len(listed)
    lines = [
        "# Events: the wording review, and citations without an archived copy",
        "",
        "Generated by `python -m atlas.content.report --write` from",
        "`content/events/migration-review.json` and `content/events/*.md`. Do not edit.",
        "",
        "## What this is",
        "",
        f"v1's {len(review['events'])} Events became files in M19 (`content/events/`), each with v1's title unchanged.",
        "v1 has titles only, so no description was migrated and none was written. An Event states what",
        "happened and when; it does not evaluate and never says one thing caused another (PLAN 5). Every",
        f"title was read twice on {review['reviewed_on']}:",
        "",
        f"- by the **word list** (`atlas/content/wordlist.py`, version {review['wordlist_version']}): a literal match of a closed",
        "  list of causal and evaluative terms;",
        "- by **Codex**, given all the titles and asked which are causal, evaluative or otherwise not a",
        "  plain statement of what happened.",
        "",
        f"**{passed} passed both and are `public`. {len(listed)} were listed by one or both and are `draft`:** a draft is in",
        "every local-profile Release and in no public-profile one. **No title was changed.** Each listed",
        "Event has a proposed wording below. They are proposals only: Alex decides, by editing the file",
        "(the `title`, and `status: public`), or by accepting a term for that Event (`accepted_terms`)",
        "where the word belongs to the thing's own name. `atlas check` fails a public Event whose text",
        "still has a listed word that is not accepted.",
        "",
        "Several proposals say *Separate Events*: v1 put two or three happenings in one title, and set",
        "side by side they read as if one explained the other. Splitting one is a new file for each",
        "part; the proposal does not do it.",
        "",
        f"## Listed for Alex ({len(listed)})",
        "",
        "| Event (v1's title, unchanged) | Word list | Codex | Proposed wording |",
        "|---|---|---|---|",
    ]
    for row in listed:
        event = by_id.get(row["id"])
        now = "" if event is None else (
            "" if event["title"] == row["title"] and event["status"] == "draft"
            else f" *(now: “{event['title']}”, {event['status']})*")
        proposed = row["proposed"] + (f" — {row['keep']}" if row.get("keep") else "")
        if row.get("codex_note"):
            proposed += f" *(Codex: {row['codex_note']})*"
        lines.append(f"| **{_cell(row['title'])}**<br>`{row['id']}`{now} | {', '.join(row['terms']) or '—'} | "
                     f"{_cell(row.get('codex', '—'))} | {_cell(proposed)} |")
    without = [(event, source) for event in events for source in event["sources"] if "no_archive" in source]
    lines += ["", f"## Citations without an archived copy ({len(without)})", "",
              "Every other citation of every Event has an `archive_url`. These are the listed exceptions",
              "(`no_archive` in the Event's file). Nothing was asked to be archived: saving a page to an",
              "archive changes a third party's record, so it is left to Alex.", "",
              "| Event | Cited address | Why there is no archived copy |", "|---|---|---|"]
    for event, source in without:
        lines.append(f"| {_cell(event['title'])}<br>`{event['id']}` | <{source['url']}> | {_cell(source['no_archive'])} |")
    hits = sum(1 for event in events if event["status"] == "public" and W.event_terms(event))
    lines += ["", "## Now", "",
              f"{len(events)} Events: {sum(1 for e in events if e['status'] == 'public')} public, "
              f"{sum(1 for e in events if e['status'] == 'draft')} draft. "
              f"Public Events whose text has an unaccepted word of the list: {hits}.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--write" in argv:
        PAGE.write_text(text, encoding="utf-8")
        print(f"wrote {PAGE}")
        return 0
    if "--check" in argv:
        if (PAGE.read_text(encoding="utf-8") if PAGE.exists() else "") != text:
            print(f"{PAGE} is out of date: run python -m atlas.content.report --write", file=sys.stderr)
            return 1
        return 0
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
